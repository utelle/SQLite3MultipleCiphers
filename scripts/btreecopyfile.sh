#!/bin/sh
# Generate btreecopyfile.c from SQLite3 amalgamation and write it to stdout.
# Usage: ./script/btreecopyfile.sh sqlite3.c >btreecopyfile.c

INPUT="$([ "$#" -eq 1 ] && echo "$1" || echo "sqlite3.c")"
if ! [ -f "$INPUT" ]; then
  echo "Usage: $0 <SQLITE3_AMALGAMATION>" >&2
  echo " e.g.: $0 sqlite3.c" >&2
  exit 1
fi

die() {
    echo "[-]" "$@" >&2
    exit 2
}

VERSION="$(sed -n 's/^#define SQLITE_VERSION[^"]*"\([0-9]\+\.[0-9]\+\.[0-9]\+\)"$/\1/p' "$INPUT")"
[ -z "$VERSION" ] && die "cannot find SQLite3 version (is '$INPUT' a valid amalgamation?)"

cat <<EOF
/*
** 2020-11-14
**
** The author disclaims copyright to this source code.  In place of
** a legal notice, here is a blessing:
**
**    May you do good and not evil.
**    May you find forgiveness for yourself and forgive others.
**    May you share freely, never taking more than you give.
**
************************************************************************
**
** This file contains an adjusted version of function sqlite3BtreeCopyFile
** to allow switching the ciphers of the codec at the right moments
** while a database is rekeyed with VACUUM.
**
** NOTE: When upgrading to a new version of SQLite3 it is strongly
** recommended to check the original function sqlite3BtreeCopyFile of the
** new version for relevant changes, and to incorporate them in the
** adjusted function below.
**
** Change 0: Rename function to sqlite3mcBtreeCopyFileForRekey()
** Change 1: Add parameter 'Codec* codec'
** Change 2: Call sqlite3mcRekeySetFinalCipher() before sqlite3_backup_finish()
**
** This code is generated by the script btreecopyfile.sh from SQLite version $VERSION amalgamation.
*/

static int sqlite3mcRekeySetFinalCipher(int, Codec*);

EOF
sed -n '/^SQLITE_PRIVATE .*int sqlite3BtreeCopyFile([^;]*$/,/^}$/p' "$INPUT" \
    | sed 's/sqlite3BtreeCopyFile(/sqlite3mcBtreeCopyFileForRekey(Codec\* codec, /' \
    | sed '/^  rc = sqlite3_backup_finish(\&b);/i \  /\* Set read/write ciphers according to return code from backup \*/\n  b.rc = sqlite3mcRekeySetFinalCipher(b.rc, codec);\n' \
    | grep "^" || die "Error generating btreecopyfile.c"
